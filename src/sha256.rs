// src/sha256.rs
//
// SHA-256 (FIPS 180-4). Ядру криптография из crates.io не нужна, поэтому
// реализация своя: около 100 строк без зависимостей.
//
// Проверена на векторах NIST: пустая строка, "abc", два длинных теста из
// FIPS-Appendice и строка из миллиона букв "a", плюс границы дополнения
// 55/56/63/64/65 байт.

/// Размер блока, который хешируется за одну итерацию сжатия.
pub const BLOCK: usize = 64;
/// Длина хеша в байтах.
pub const DIGEST: usize = 32;

const K: [u32; 64] = [
    0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4, 0xab1c5ed5,
    0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174,
    0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da,
    0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967,
    0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85,
    0xa2bfe8a1, 0xa81a664b, 0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070,
    0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
    0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2,
];

const H0: [u32; 8] = [
    0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19,
];

fn compress(h: &mut [u32; 8], block: &[u8; BLOCK]) {
    let mut w = [0u32; 64];
    for i in 0..16 {
        w[i] = u32::from_be_bytes([block[i * 4], block[i * 4 + 1], block[i * 4 + 2], block[i * 4 + 3]]);
    }
    for i in 16..64 {
        let s0 = w[i - 15].rotate_right(7) ^ w[i - 15].rotate_right(18) ^ (w[i - 15] >> 3);
        let s1 = w[i - 2].rotate_right(17) ^ w[i - 2].rotate_right(19) ^ (w[i - 2] >> 10);
        w[i] = w[i - 16]
            .wrapping_add(s0)
            .wrapping_add(w[i - 7])
            .wrapping_add(s1);
    }
    let (mut a, mut b, mut c, mut d, mut e, mut f, mut g, mut hh) =
        (h[0], h[1], h[2], h[3], h[4], h[5], h[6], h[7]);
    for i in 0..64 {
        let s1 = e.rotate_right(6) ^ e.rotate_right(11) ^ e.rotate_right(25);
        let ch = (e & f) ^ ((!e) & g);
        let t1 = hh
            .wrapping_add(s1)
            .wrapping_add(ch)
            .wrapping_add(K[i])
            .wrapping_add(w[i]);
        let s0 = a.rotate_right(2) ^ a.rotate_right(13) ^ a.rotate_right(22);
        let maj = (a & b) ^ (a & c) ^ (b & c);
        let t2 = s0.wrapping_add(maj);
        hh = g; g = f; f = e;
        e = d.wrapping_add(t1);
        d = c; c = b; b = a;
        a = t1.wrapping_add(t2);
    }
    h[0] = h[0].wrapping_add(a);
    h[1] = h[1].wrapping_add(b);
    h[2] = h[2].wrapping_add(c);
    h[3] = h[3].wrapping_add(d);
    h[4] = h[4].wrapping_add(e);
    h[5] = h[5].wrapping_add(f);
    h[6] = h[6].wrapping_add(g);
    h[7] = h[7].wrapping_add(hh);
}

/// Состояние потокового SHA-256 (то же, что hashlib.sha256).
///
///`hash` выше годится на один вызов, а PBKDF2-HMAC строит тысячи
/// хешей подряд на одной и той же ключевой подушке. Держать поток
/// в структуре = без новых Vec на каждом раунде.
pub struct Sha256State {
    h: [u32; 8],
    buf: [u8; BLOCK],
    buf_len: usize,
    total_len: u64,
}

impl Sha256State {
    pub fn new() -> Self {
        Sha256State { h: H0, buf: [0; BLOCK], buf_len: 0, total_len: 0 }
    }

    pub fn update(&mut self, mut data: &[u8]) {
        self.total_len = self.total_len.wrapping_add(data.len() as u64);
        if self.buf_len > 0 {
            let need = BLOCK - self.buf_len;
            let take = need.min(data.len());
            self.buf[self.buf_len..self.buf_len + take].copy_from_slice(&data[..take]);
            self.buf_len += take;
            data = &data[take..];
            if self.buf_len == BLOCK {
                let b = core::mem::replace(&mut self.buf, [0u8; BLOCK]);
                compress(&mut self.h, &b);
                self.buf_len = 0;
            }
        }
        while data.len() >= BLOCK {
            let mut b = [0u8; BLOCK];
            b.copy_from_slice(&data[..BLOCK]);
            compress(&mut self.h, &b);
            data = &data[BLOCK..];
        }
        if !data.is_empty() {
            self.buf[..data.len()].copy_from_slice(data);
            self.buf_len = data.len();
        }
    }

    pub fn finalize(mut self) -> [u8; DIGEST] {
        let bits = self.total_len.wrapping_mul(8);
        self.buf[self.buf_len] = 0x80;
        self.buf_len += 1;
        if self.buf_len > BLOCK - 8 {
            for i in self.buf_len..BLOCK { self.buf[i] = 0; }
            let b = core::mem::replace(&mut self.buf, [0u8; BLOCK]);
            compress(&mut self.h, &b);
            self.buf_len = 0;
        }
        for i in self.buf_len..BLOCK - 8 { self.buf[i] = 0; }
        self.buf[BLOCK - 8..].copy_from_slice(&bits.to_be_bytes());
        let b = core::mem::replace(&mut self.buf, [0u8; BLOCK]);
        compress(&mut self.h, &b);

        let mut out = [0u8; DIGEST];
        for i in 0..8 {
            out[i * 4..i * 4 + 4].copy_from_slice(&self.h[i].to_be_bytes());
        }
        out
    }
}

/// Хеш строки. Возвращает 32 байта.
pub fn hash(data: &[u8]) -> [u8; DIGEST] {
    let mut st = Sha256State::new();
    st.update(data);
    st.finalize()
}

pub fn hex(d: &[u8]) -> alloc::string::String {
    const D: &[u8; 16] = b"0123456789abcdef";
    let mut s = alloc::string::String::with_capacity(d.len() * 2);
    for &b in d {
        s.push(D[(b >> 4) as usize] as char);
        s.push(D[(b & 0xf) as usize] as char);
    }
    s
}
