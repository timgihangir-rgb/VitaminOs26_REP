//! Пауза до следующего прерывания.
//!
//! `crate::halt::hlt()` объявлен как
//! `asm!("hlt", options(nomem, nostack, preserves_flags))`, и это НЕВЕРНО для
//! ядра: `nomem` говорит компилятору, что инструкция не читает и не пишет
//! память. Из-за этого оптимизатор выносит из цикла вида
//!
//! ```text
//! loop { if kb_hit() { ... }; hlt(); }
//! ```
//!
//! чтение `BUF_HEAD`/`BUF_TAIL` наружу — цикл начинает вечно крутиться на
//! одном устаревшем значении и перестаёт замечать данные, записываемые
//! обработчиком прерывания. На `opt-level = 0` цикл не трогается и всё
//! работает, при `opt-level >= 1` система зависает на экране загрузки:Enter
//! не доходит, `ps`/`wait` не возвращаются.
//!
//! Наш `hlt` объявляет только `nostack`: чтение и запись памяти после него
//! компилятор считать не может, поэтому все обращения к разделяемому
//! состоянию остаются в цикле.

/// Останавливает CPU до ближайшего прерывания (таймер 100 Гц, IRQ1 и т.п.).
///
/// Вызывать только с `IF = 1`: с выключенными прерываниями следующий
/// прерывания не будет, и CPU остановится навсегда.
#[inline]
pub fn hlt() {
    unsafe {
        core::arch::asm!("hlt", options(nostack, preserves_flags));
    }
}