/* programs/common/vgasize.h
 *
 * Размер текстовой сетки для ring 3-программ.
 *
 * Раньше сетка была везде зашита как 80x30, и это работало: композитор
 * рис/text-буфер 0xB8000 тоже был ровно 80x30. Теперь композитор выбирает
 * сетку под разрешение монитора (см. `fit_grid` в src/fb.rs) — на 1280x800
 * это 80x25 в масштабе 2x, на 1920x1080 — 120x33. Ядро публикует итог в
 * слотах GRID_COLS/GRID_ROWS (см. `src/progabi.rs`), и программа читает их
 * один раз при старте.
 *
 * Зачем это нужно программе: очистка экрана, рамки, статусные строки и всё,
 * что считает «а где низ экрана», обязаны спрашивать размер, а не
 * ориентироваться на 80x30. Иначе на 120x33 программа очистит только левый
 * верхний угол и оставит мусор, а на 80x25 нарисует за нижней границей.
 *
 * Пока слоты пусты (ядро не включило композитор — система в текстовом
 * режиме), остаются 80x30, то есть поведение ровно прежнее.
 *
 * Подключать нужно в файле, который вызывает `vga_read_grid()` из `_start`
 * ДО первого обращения к 0xB8000.
 */
#ifndef VITASIZE_H
#define VITASIZE_H

#define GRID_COLS_P 0x78A0 /* u32, см. progabi::GRID_COLS */
#define GRID_ROWS_P 0x78A4 /* u32, см. progabi::GRID_ROWS */

static unsigned g_screen_w = 80;
static unsigned g_screen_h = 30;

/* Читает сетку, объявленную ядром. Одна строка в начале _start. */
static void vga_read_grid(void)
{
    unsigned c = *(volatile unsigned *)GRID_COLS_P;
    unsigned r = *(volatile unsigned *)GRID_ROWS_P;
    /* Границы — и фильтр от мусора в слотах, и защита от абсурда: программа,
     * рисующая по этим числам, не должна выйти за тень экрана даже если
     * слоты почему-то испорчены. Реальные сетки: 80x25 ... 200x100. */
    if (c >= 16 && c <= 1024)
        g_screen_w = c;
    if (r >= 4 && r <= 512)
        g_screen_h = r;
}

#endif /* VITASIZE_H */
